/* Plainpage release builds: the no-updater edition, one installer per
 * architecture, for macOS and Windows.
 *
 *   pnpm release            both platforms
 *   pnpm release mac        DMGs only (arm64, x64)
 *   pnpm release win        NSIS installers only (x64, arm64)
 *
 * Builds with FOOLSCAP_EDITION=store, so electron-updater is never even
 * imported; and from a derived config with `publish: null`, so no
 * app-update.yml feed file lands in the bundle (see dist-store.cjs for why
 * only a top-level null does that). Builds are unsigned: macOS gets the
 * ad-hoc seal from scripts/ad-hoc-sign.cjs, Windows none. Windows
 * installers build fine from a Mac. */
const { execFileSync } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const which = process.argv[2] ?? 'all'
if (!['all', 'mac', 'win'].includes(which)) {
  console.error(`release: expected mac, win, or nothing — got ${which}`)
  process.exit(2)
}

const PUBLISH_TOKENS = ['GH_TOKEN', 'GITHUB_TOKEN', 'GITLAB_TOKEN', 'KEYGEN_TOKEN', 'BITBUCKET_TOKEN', 'BT_TOKEN']
const run = (cmd, args, env = {}) => {
  const clean = { ...process.env, CSC_IDENTITY_AUTO_DISCOVERY: 'false', ...env }
  for (const name of PUBLISH_TOKENS) delete clean[name]
  execFileSync(cmd, args, { cwd: root, stdio: 'inherit', env: clean })
}
const fail = (msg) => {
  console.error(`\nrelease: ${msg}`)
  process.exit(1)
}

run('pnpm', ['exec', 'electron-vite', 'build'], { FOOLSCAP_EDITION: 'store' })
const main = fs.readFileSync(path.join(root, 'out/main/index.js'), 'utf8')
if (main.includes('electron-updater')) fail('out/main/index.js still references electron-updater')

const yaml = require(require.resolve('js-yaml', { paths: [path.dirname(require.resolve('electron-builder/package.json'))] }))
const config = yaml.load(fs.readFileSync(path.join(root, 'electron-builder.yml'), 'utf8'))
config.publish = null
config.dmg = { ...config.dmg, artifactName: '${productName}-${version}-${arch}.${ext}' }
config.nsis = { ...config.nsis, artifactName: '${productName}-Setup-${version}-${arch}.${ext}' }
fs.mkdirSync(path.join(root, 'dist'), { recursive: true })
const releaseConfig = path.join(root, 'dist/electron-builder.release.yml')
fs.writeFileSync(releaseConfig, '# Generated by scripts/dist-plainpage.cjs — do not edit.\n' + yaml.dump(config))

const builder = (args) => run('pnpm', ['exec', 'electron-builder', '--config', releaseConfig, '--publish', 'never', ...args])
const noFeed = (dir) => {
  const hits = []
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name)
      if (e.name === 'app-update.yml') hits.push(p)
      else if (e.isDirectory() && !e.isSymbolicLink() && !e.name.endsWith('.asar')) walk(p)
    }
  }
  walk(dir)
  if (hits.length) fail(`feed file in the bundle: ${hits.join(', ')}`)
}

try {
  if (which !== 'win') {
    for (const arch of ['arm64', 'x64']) {
      builder(['--mac', 'dmg', `--${arch}`])
      noFeed(path.join(root, arch === 'x64' ? 'dist/mac' : `dist/mac-${arch}`))
    }
  }
  if (which !== 'mac') {
    // One arch per run: together, NSIS makes a single installer carrying both.
    for (const arch of ['x64', 'arm64']) {
      builder(['--win', 'nsis', `--${arch}`])
      noFeed(path.join(root, arch === 'x64' ? 'dist/win-unpacked' : `dist/win-${arch}-unpacked`))
    }
  }
} finally {
  // Leave out/ as the direct edition, the default everything else expects.
  run('pnpm', ['exec', 'electron-vite', 'build'])
}

const made = fs.readdirSync(path.join(root, 'dist')).filter((f) => f.startsWith(`${pkg.productName}-`) && /\.(dmg|exe)$/.test(f) && f.includes(pkg.version))
console.log(`\nrelease: ${pkg.productName} ${pkg.version}, no updater, no feed file`)
for (const f of made) console.log(`release: dist/${f}`)
